// Synthetic, public test keys only. Never use these scalars for real chat devices.
import { createECDH } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
import { seal, unseal, publicDevice, fingerprint, openAttachment } from '../lib/crypto/chat.ts';

const root = new URL('../', import.meta.url);
async function device(n, user) {
  const scalar = Buffer.alloc(32);
  scalar[31] = n;
  const ecdh = createECDH('prime256v1');
  ecdh.setPrivateKey(scalar);
  const point = ecdh.getPublicKey();
  const public_key = {
    kty: 'EC',
    crv: 'P-256',
    x: point.subarray(1, 33).toString('base64url'),
    y: point.subarray(33).toString('base64url'),
  };
  const privateKey = await crypto.subtle.importKey(
    'jwk',
    { ...public_key, d: scalar.toString('base64url'), ext: true },
    { name: 'ECDH', namedCurve: 'P-256' },
    false,
    ['deriveBits'],
  );
  return {
    id: `00000000-0000-4000-8000-${String(n).padStart(12, '0')}`,
    user_id: user,
    label: 'Dispositivo di test M0.5',
    public_key,
    privateKey,
  };
}
const web = await device(1, '00000000-0000-4000-8000-000000000011');
const phone = await device(2, '00000000-0000-4000-8000-000000000012');
const webSecond = await device(3, web.user_id);
const fixturePath = new URL('ios/ChatCrypto/interop-fixtures.json', root);
const [mode, reportPath] = process.argv.slice(2);
if (mode === 'generate') {
  const vectors = [];
  for (let i = 0; i < 3; i++) {
    const context = {
      id: `10000000-0000-4000-8000-${String(i).padStart(12, '0')}`,
      sender_id: web.user_id,
      recipient_id: phone.user_id,
      expires_at: i === 2 ? '2099-01-02T03:04:05.000Z' : null,
      retention: i === 2 ? 'device' : 'synced',
      ...(i === 0 ? {} : { revision: i - 1 }),
    };
    const body = `Web → iPhone ${i}: caffè, 漢字, 👩🏽‍💻, /, \", \\, \n`;
    const media =
      i === 2
        ? new File([new Uint8Array([0, 1, 2, 127, 128, 255])], 'fixture.webp', {
            type: 'image/webp',
          })
        : null;
    const packet = await seal(web, [web, phone, webSecond].map(publicDevice), context, body, media);
    vectors.push({
      context,
      packet: packet.sealed,
      body,
      attachment: packet.attachment
        ? Buffer.from(await packet.attachment.arrayBuffer()).toString('base64')
        : null,
      attachment_clear: media ? Buffer.from(await media.arrayBuffer()).toString('base64') : null,
      reply_context: {
        ...context,
        id: `20000000-0000-4000-8000-${String(i).padStart(12, '0')}`,
        sender_id: phone.user_id,
        recipient_id: web.user_id,
      },
      reply_body: `iPhone → Web ${i}: integrità ✓, emoji 🔐 e accenti è à`,
    });
  }
  const fixture = {
    fixture_id: crypto.randomUUID(),
    phone: publicDevice(phone),
    phone_test_key: Buffer.from(new Uint8Array([...Array(31).fill(0), 2])).toString('base64'),
    web: publicDevice(web),
    web_second: publicDevice(webSecond),
    fingerprints: { web: await fingerprint(web), phone: await fingerprint(phone) },
    vectors,
  };
  const json = JSON.stringify(fixture, null, 2);
  await writeFile(fixturePath, json + '\n');
  await writeFile(
    new URL('ios/ChatCrypto/Sources/SNChatCrypto/InteropFixtures.swift', root),
    `// Generated by scripts/ios-crypto-interop.mjs generate. Public test keys, never production keys.\n#if DEBUG\nimport Foundation\nenum InteropFixtures {\n    static let data = Data(#\"\"\"\n${json}\n\"\"\"#.utf8)\n}\n#endif\n`,
  );
  console.log(`Generated ${vectors.length} Web Crypto fixtures (public synthetic keys).`);
} else if (mode === 'verify' && reportPath) {
  const fixture = JSON.parse(await readFile(fixturePath, 'utf8'));
  const report = JSON.parse(await readFile(reportPath, 'utf8'));
  assert.equal(report.fixture_id, fixture.fixture_id, 'report must match current fixture set');
  assert.equal(report.status, 'passed');
  assert.equal(report.replies.length, fixture.vectors.length);
  for (let i = 0; i < report.replies.length; i++) {
    const reply = report.replies[i],
      vector = fixture.vectors[i];
    assert.deepEqual(reply.sealed.context, vector.reply_context);
    for (const target of [web, webSecond, phone]) {
      const clear = await unseal(target, vector.reply_context, reply.sealed);
      assert.equal(clear.body, vector.reply_body);
      if (vector.attachment_clear) {
        assert.ok(clear.media);
        const bytes = await openAttachment(
          vector.reply_context,
          clear.media,
          Buffer.from(reply.attachment, 'base64'),
        );
        assert.equal(
          Buffer.from(await bytes.arrayBuffer()).toString('base64'),
          vector.attachment_clear,
        );
      } else assert.equal(clear.media, null);
    }
    await assert.rejects(
      unseal(
        web,
        {
          ...vector.reply_context,
          retention: vector.reply_context.retention === 'synced' ? 'device' : 'synced',
        },
        reply.sealed,
      ),
    );
    assert.equal(JSON.stringify(reply).includes(vector.reply_body), false);
  }
  console.log(
    JSON.stringify({
      platform: report.platform,
      fixture_id: report.fixture_id,
      swift_checks: report.checks.length,
      web_verified_replies: report.replies.length,
      recipients_per_reply: 3,
      attachments: 'verified',
      status: 'passed',
    }),
  );
} else {
  throw new Error('Usage: node scripts/ios-crypto-interop.mjs generate | verify <report.json>');
}
