const italian = Object.fromEntries(
  Object.entries(english).map(([source, target]) => [target, source]),
);

const patterns: Array<[RegExp, (...parts: string[]) => string]> = [
  [/^(\d+) persone$/, (count) => `${count} people`],
  [/^(\d+) post nella piazza$/, (count) => `${count} post${count === '1' ? '' : 's'} in the feed`],
  [/^Opzione (\d+)$/, (number) => `Option ${number}`],
  [/^Reazione (.+)$/, (reaction) => `${reaction} reaction`],
  [/^Rispondi a (.+)…$/, (name) => `Reply to ${name}…`],
  [/^Ruolo di (.+)$/, (name) => `${name}’s role`],
  [/^Rimuovi (.+) dalla cerchia$/, (name) => `Remove ${name} from the circle`],
  [/^Modifica (.+)$/, (name) => `Edit ${name}`],
  [/^Scade tra (.+)$/, (time) => `Expires in ${time}`],
];

export function translateInterface(value: string, language: AppLanguage): string {
  if (language === 'it') return italian[value] ?? value;
  const direct = english[value];
  if (direct) return direct;
  for (const [pattern, replacement] of patterns) {
    const match = value.match(pattern);
    if (match) return replacement(...match.slice(1));
  }
  return value;
}
